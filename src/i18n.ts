export function makeI18n(lang: Lang, currency: Currency) {
  const dict: Record<Key, string> = lang === 'ar' ? ar : en
  // Western 0-9 in both languages (DESIGN.md): ar-EG defaults to Arabic-Indic digits, so the numbering system is pinned.
  const locale = lang === 'ar' ? 'ar-EG-u-nu-latn' : 'en-US'
  const num = new Intl.NumberFormat(locale)
  const plural = new Intl.PluralRules(lang === 'ar' ? 'ar' : 'en')
  const money = new Intl.NumberFormat(locale, { style: 'currency', currency, maximumFractionDigits: 2, minimumFractionDigits: 0 })
  const df = (o: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat(locale, o)
  const date = df({ day: 'numeric', month: 'short', year: 'numeric' })
  const dateTime = df({ day: 'numeric', month: 'short', hour: 'numeric', minute: '2-digit' })
  const time = df({ hour: 'numeric', minute: '2-digit' })
  const shortDay = df({ day: 'numeric', month: 'short' })
  const hour = df({ hour: 'numeric' })
  const monthName = df({ month: 'long', year: 'numeric' })
  const weekday = df({ weekday: 'long' })

  const t = (k: Key, p: Record<string, string | number> = {}) =>
    dict[k].replace(/\{(\w+)\}/g, (_, x: string) => String(typeof p[x] === 'number' ? num.format(p[x] as number) : p[x] ?? ''))

  return {
    lang,
    dir: lang === 'ar' ? ('rtl' as const) : ('ltr' as const),
    t,
    num: (n: number) => num.format(n),
    money: (n: number) => money.format(n),
    pct: (n: number) => new Intl.NumberFormat(locale, { style: 'percent', maximumFractionDigits: 0 }).format(n),
    date: (iso: string) => date.format(new Date(iso)),
    dateTime: (iso: string) => dateTime.format(new Date(iso)),
    time: (iso: string) => time.format(new Date(iso)),
    shortDay: (d: Date) => shortDay.format(d),
    hour: (h: number) => hour.format(new Date(2000, 0, 1, h)),
    /** month: yyyy-mm or yyyy-mm-dd */
    month: (m: string) => monthName.format(new Date(Number(m.slice(0, 4)), Number(m.slice(5, 7)) - 1, 1)),
    /** yyyy-mm-dd, shown without time-zone shifts */
    day: (d: string) => date.format(new Date(Number(d.slice(0, 4)), Number(d.slice(5, 7)) - 1, Number(d.slice(8, 10)))),
    /** 0 = Sunday .. 6 = Saturday (2023-01-01 was a Sunday) */
    weekday: (n: number) => weekday.format(new Date(2023, 0, 1 + n)),
    seatName: (s: Seat) => s.label || t(s.kind === 'sofa' ? 'seat.sofaN' : 'seat.chairN', { n: s.number }),
    /** "5 minutes" with real plural agreement: Arabic needs دقيقتان / دقائق / دقيقة by count (BACKLOG). */
    minutes: (n: number) => {
      const form = plural.select(n)
      if (lang === 'en') return `${num.format(n)} ${form === 'one' ? 'minute' : 'minutes'}`
      if (form === 'two') return 'دقيقتان'
      if (form === 'one') return 'دقيقة واحدة'
      return `${num.format(n)} ${form === 'few' ? 'دقائق' : 'دقيقة'}`
    },
    serviceName: (s?: Service) => (s ? (lang === 'ar' ? s.nameAr : s.nameEn) : t('floor.noService')),
  }
}

export type I18n = ReturnType<typeof makeI18n>
